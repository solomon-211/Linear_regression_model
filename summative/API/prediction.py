"""FastAPI service for predicting the average learning score of children in a Ugandan village.

Routes
- POST /predict : validates the 12 input variables and returns the predicted score (0-10) with a support priority
- POST /retrain : accepts a CSV of new village records, retrains the model and applies it immediately
- GET  /docs    : Swagger UI generated by FastAPI

Local run: uvicorn prediction:app --reload
"""

import io
import os
import threading
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Literal

import joblib
import numpy as np
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import RedirectResponse
from pydantic import BaseModel, ConfigDict, Field, ValidationError
from sklearn.base import clone
from sklearn.linear_model import SGDRegressor
from sklearn.metrics import mean_squared_error

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "best_model.pkl"
DATA_PATH = BASE_DIR / "training_data.csv"

FEATURES = [
    "region", "area", "pct_mother_secondary", "pct_private_school", "pct_paid_tuition",
    "pct_preschool", "pct_electricity", "pct_phone", "pct_toilet", "pct_three_meals",
    "avg_household_size", "avg_child_age",
]
TARGET = "avg_learning_score"


# ---------------------------------------------------------------------------
# Request / response schemas
# ---------------------------------------------------------------------------
class VillageInput(BaseModel):
    """Community characteristics of one Ugandan village."""

    # strict=True: text in a number field (or a number in a text field) is a type error, not silently converted.
    # extra="forbid": unknown fields are rejected.
    model_config = ConfigDict(
        strict=True,
        extra="forbid",
        json_schema_extra={
            "example": {
                "region": "Central", "area": "Rural", "pct_mother_secondary": 27.8, "pct_private_school": 0.0,
                "pct_paid_tuition": 0.0, "pct_preschool": 4.3, "pct_electricity": 22.2, "pct_phone": 44.4,
                "pct_toilet": 66.7, "pct_three_meals": 33.3, "avg_household_size": 4.78, "avg_child_age": 10.11,
            }
        },
    )

    region: Literal["Central", "Eastern", "North", "Western"] = Field(description="Region of Uganda")
    area: Literal["Rural", "Urban"] = Field(description="Rural or urban village")
    pct_mother_secondary: float = Field(ge=0, le=100, description="% of children whose mother completed secondary school")
    pct_private_school: float = Field(ge=0, le=100, description="% of enrolled children attending a private school")
    pct_paid_tuition: float = Field(ge=0, le=100, description="% of children receiving paid extra tuition")
    pct_preschool: float = Field(ge=0, le=100, description="% of children who attended preschool")
    pct_electricity: float = Field(ge=0, le=100, description="% of households with electricity")
    pct_phone: float = Field(ge=0, le=100, description="% of households owning a mobile phone")
    pct_toilet: float = Field(ge=0, le=100, description="% of households with a toilet")
    pct_three_meals: float = Field(ge=0, le=100, description="% of households eating three or more meals a day")
    avg_household_size: float = Field(ge=1, le=20, description="Average number of people per household")
    avg_child_age: float = Field(ge=6, le=16, description="Average age of tested children (Uwezo tests ages 6-16)")


class PredictionOutput(BaseModel):
    predicted_learning_score: float = Field(description="Predicted average learning score of the village's children (0-10)")
    support_priority: str = Field(description="High, Medium or Low priority for learning support")
    message: str


class RetrainOutput(BaseModel):
    message: str
    method: str
    rows_received: int
    rows_used: int
    total_training_rows: int
    mse_on_new_rows_before: float
    mse_on_new_rows_after: float


# ---------------------------------------------------------------------------
# Model state (loaded at startup, replaced in place by /retrain)
# ---------------------------------------------------------------------------
state: dict = {}
lock = threading.Lock()


@asynccontextmanager
async def lifespan(app: FastAPI):
    # always start from the model committed to the repository
    state["model"] = joblib.load(MODEL_PATH)
    state["data"] = pd.read_csv(DATA_PATH)
    yield


app = FastAPI(
    title="Uganda Village Learning Predictor",
    description=(
        "Predicts the average reading-and-maths learning score (0-10) of children in a Ugandan village from community "
        "characteristics, so that education officers and NGOs can direct learning support where it is most needed. "
        "Model: linear regression trained on Uwezo Uganda 2015 data (3,219 villages)."
    ),
    version="1.0.0",
    lifespan=lifespan,
)

# ---------------------------------------------------------------------------
# CORS
# What is allowed:
#   - Origins: only the browser origins listed below - the deployed Render URL (so Swagger UI at /docs works
#     from the browser) and the local Flutter web debug addresses (flutter run -d chrome --web-port 5000).
#     Extra origins can be added with the ALLOWED_ORIGINS environment variable (comma-separated), with no code change.
#   - Methods: only GET (docs) and POST (/predict, /retrain), the only methods this API uses.
#   - Headers: only Content-Type (needed for JSON bodies and file uploads) and Accept.
# What is restricted and why:
#   - No wildcard "*" for origins: other websites open in a user's browser cannot call this API,
#     which stops unknown sites from using the model or sending files to /retrain.
#   - PUT/DELETE/PATCH and custom headers are blocked because nothing here needs them (smallest attack surface).
#   - allow_credentials=False: the API uses no cookies or login sessions, so browsers must not send them.
# Note: CORS is enforced by browsers only. The Flutter mobile app is not a browser, so it is not affected.
# ---------------------------------------------------------------------------
DEFAULT_ORIGINS = [
    "https://uganda-learning-predictor.onrender.com",
    "http://localhost:5000",
    "http://127.0.0.1:5000",
]
extra_origins = [o.strip() for o in os.getenv("ALLOWED_ORIGINS", "").split(",") if o.strip()]

app.add_middleware(
    CORSMiddleware,
    allow_origins=DEFAULT_ORIGINS + extra_origins,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
    allow_credentials=False,
)


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------
def support_priority(score: float) -> tuple[str, str]:
    if score < 4:
        return "High", "Most children are likely below basic reading and numeracy. Prioritise this village for learning support."
    if score < 6:
        return "Medium", "Children are likely to read words or a paragraph and add or subtract. Targeted support is recommended."
    return "Low", "Children are likely to have relatively strong basic skills compared with other villages."


@app.get("/", include_in_schema=False)
def root():
    return RedirectResponse(url="/docs")


@app.post("/predict", response_model=PredictionOutput)
def predict(village: VillageInput):
    row = pd.DataFrame([village.model_dump()])[FEATURES]
    with lock:
        score = float(state["model"].predict(row)[0])
    score = round(min(max(score, 0.0), 10.0), 2)
    priority, message = support_priority(score)
    return PredictionOutput(predicted_learning_score=score, support_priority=priority, message=message)


@app.post("/retrain", response_model=RetrainOutput)
async def retrain(file: UploadFile = File(description="CSV with the same columns as the training data: the 12 features plus avg_learning_score.")):
    if not (file.filename or "").lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="Please upload a .csv file.")
    try:
        new = pd.read_csv(io.BytesIO(await file.read()))
    except Exception:
        raise HTTPException(status_code=400, detail="Could not read the file as CSV.")

    missing = [c for c in FEATURES + [TARGET] if c not in new.columns]
    if missing:
        raise HTTPException(status_code=422, detail=f"CSV is missing required columns: {missing}")
    rows_received = len(new)
    new = new[FEATURES + [TARGET]].dropna()

    # validate every row with the same rules as /predict, plus a valid target
    errors = []
    for line, rec in zip(new.index + 2, new.to_dict("records")):  # +2 = header row + 1-based numbering
        try:
            VillageInput.model_validate({k: _py(rec[k]) for k in FEATURES}, strict=False)
        except ValidationError as e:
            err = e.errors()[0]
            errors.append(f"line {line}: {'.'.join(str(p) for p in err['loc'])}: {err['msg']}")
            continue
        if not 0 <= rec[TARGET] <= 10:
            errors.append(f"line {line}: avg_learning_score must be between 0 and 10")
    if errors:
        raise HTTPException(status_code=422, detail={"message": f"{len(errors)} invalid row(s)", "errors": errors[:10]})
    if new.empty:
        raise HTTPException(status_code=422, detail="No usable rows in the CSV.")

    with lock:
        model = state["model"]
        X_new, y_new = new[FEATURES], new[TARGET]
        mse_before = mean_squared_error(y_new, model.predict(X_new))
        combined = pd.concat([state["data"], new], ignore_index=True)

        if isinstance(model.named_steps["model"], SGDRegressor):
            # gradient-descent model: continue training the saved model on the new rows only
            Xt = model.named_steps["preprocess"].transform(X_new)
            for _ in range(20):
                model.named_steps["model"].partial_fit(Xt, y_new)
            updated, method = model, "SGDRegressor: continued training on the new rows with partial_fit"
        else:
            # any other model: refit the full pipeline on the original data plus the new rows
            updated = clone(model).fit(combined[FEATURES], combined[TARGET])
            method = f"{type(model.named_steps['model']).__name__}: refit on original data + new rows"

        mse_after = mean_squared_error(y_new, updated.predict(X_new))
        state["model"], state["data"] = updated, combined  # /predict uses the new model immediately
        try:
            joblib.dump(updated, MODEL_PATH)
            combined.to_csv(DATA_PATH, index=False)
        except OSError:
            pass  # read-only disk is fine: the model in memory is already updated

    return RetrainOutput(
        message="Model retrained. /predict now uses the updated model.",
        method=method,
        rows_received=rows_received,
        rows_used=len(new),
        total_training_rows=len(combined),
        mse_on_new_rows_before=round(mse_before, 4),
        mse_on_new_rows_after=round(mse_after, 4),
    )


def _py(v):
    """Convert numpy values to plain Python values so Pydantic can validate CSV rows."""
    if isinstance(v, np.integer):
        return int(v)
    if isinstance(v, np.floating):
        return float(v)
    return v
