"""FastAPI service that predicts next month's retail food price per kg in Rwandan markets and refugee camps.

Routes
- POST /predict : validates the 8 input variables and returns the predicted price (RWF per kg) with a price alert
- POST /retrain : accepts a CSV of new prices, updates the model (see retrain.py) and applies it immediately
- GET  /docs    : Swagger UI generated by FastAPI

Local run: uvicorn prediction:app --reload
"""

import io
import os
import threading
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Literal

import joblib
import numpy as np
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import RedirectResponse
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from retrain import retrain_model

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "best_model.pkl"
DATA_PATH = BASE_DIR / "training_data.csv"

FEATURES = [
    "commodity", "province", "market_type", "distance_to_kigali_km",
    "year", "month", "price_last_month", "national_median_last_month",
]
TARGET = "price"

Commodity = Literal[
    "Bananas", "Beans (dry)", "Cabbage", "Cassava", "Cassava flour", "Cassava leaves", "Fish (dry)",
    "Maize", "Maize flour", "Maize flour (imported)", "Meat (beef)", "Potatoes", "Potatoes (Irish)",
    "Rice (imported)", "Rice (local)", "Rice (long grain, high quality, local)", "Salt", "Sorghum", "Sugar",
]
Province = Literal["Eastern Province", "Kigali City", "Northern Province", "Southern Province", "Western Province"]


# ---------------------------------------------------------------------------
# Request / response schemas
# ---------------------------------------------------------------------------
class MarketInput(BaseModel):
    """One food item in one market, with what is known at the end of the previous month."""

    # strict=True: text in a number field (or a number in a text field) is a type error, not silently converted.
    # extra="forbid": unknown fields are rejected.
    model_config = ConfigDict(
        strict=True,
        extra="forbid",
        json_schema_extra={
            "example": {
                "commodity": "Cassava", "province": "Eastern Province", "market_type": "Refugee camp",
                "distance_to_kigali_km": 44.8, "year": 2025, "month": 9,
                "price_last_month": 362.5, "national_median_last_month": 350.0,
            }
        },
    )

    commodity: Commodity = Field(description="Food item (one of the 19 in the training data)")
    province: Province = Field(description="Province of the market")
    market_type: Literal["Refugee camp", "Town market"] = Field(description="Refugee camp market or town market")
    distance_to_kigali_km: float = Field(ge=0, le=150, description="Straight-line distance from Kigali in km")
    year: int = Field(ge=2018, le=2030, description="Year of the month being predicted")
    month: int = Field(ge=1, le=12, description="Month being predicted (1 = January)")
    price_last_month: float = Field(gt=0, le=20000, description="Retail price per kg in this market last month (RWF)")
    national_median_last_month: float = Field(gt=0, le=20000, description="Median retail price per kg across Rwanda last month (RWF)")


class PredictionOutput(BaseModel):
    predicted_price_rwf_per_kg: float = Field(description="Predicted retail price per kg for the month (RWF)")
    change_vs_last_month_pct: float = Field(description="Change from last month's price in this market (%)")
    price_alert: str = Field(description="Rising, Stable or Falling")
    message: str


class RetrainOutput(BaseModel):
    message: str
    method: str
    rows_received: int
    rows_used: int
    total_training_rows: int
    mse_on_new_rows_before: float
    mse_on_new_rows_after: float


# ---------------------------------------------------------------------------
# Model state (loaded at startup, replaced in place by /retrain)
# ---------------------------------------------------------------------------
state: dict = {}
lock = threading.Lock()


@asynccontextmanager
async def lifespan(app: FastAPI):
    # always start from the model committed to the repository
    state["model"] = joblib.load(MODEL_PATH)
    state["data"] = pd.read_csv(DATA_PATH)
    yield


app = FastAPI(
    title="Rwanda Food Price Predictor",
    description=(
        "Predicts next month's retail price per kg of 19 foods in Rwandan town markets and refugee camps, so that "
        "WFP cash-transfer officers can check whether refugees' food assistance still covers a basic food basket. "
        "Model: SGDRegressor trained on WFP market prices observed from 2018 to 2025 (16,735 prices)."
    ),
    version="1.0.0",
    lifespan=lifespan,
)

# ---------------------------------------------------------------------------
# CORS
# What is allowed:
#   - Origins: only the browser origins listed below - the deployed Render URL (so Swagger UI at /docs works
#     from the browser) and the local Flutter web debug addresses (flutter run -d chrome --web-port 5000).
#     Extra origins can be added with the ALLOWED_ORIGINS environment variable (comma-separated), with no code change.
#   - Methods: only GET (docs) and POST (/predict, /retrain), the only methods this API uses.
#   - Headers: only Content-Type (needed for JSON bodies and file uploads) and Accept.
# What is restricted and why:
#   - No wildcard "*" for origins: other websites open in a user's browser cannot call this API,
#     which stops unknown sites from using the model or sending files to /retrain.
#   - PUT/DELETE/PATCH and custom headers are blocked because nothing here needs them (smallest attack surface).
#   - allow_credentials=False: the API uses no cookies or login sessions, so browsers must not send them.
# Note: CORS is enforced by browsers only. The Flutter mobile app is not a browser, so it is not affected.
# ---------------------------------------------------------------------------
DEFAULT_ORIGINS = [
    "https://linear-regression-model-3xle.onrender.com",
    "http://localhost:5000",
    "http://127.0.0.1:5000",
]
extra_origins = [o.strip() for o in os.getenv("ALLOWED_ORIGINS", "").split(",") if o.strip()]

app.add_middleware(
    CORSMiddleware,
    allow_origins=DEFAULT_ORIGINS + extra_origins,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
    allow_credentials=False,
)


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------
def price_alert(change_pct: float) -> tuple[str, str]:
    if change_pct > 5:
        return "Rising", "The price is expected to rise by more than 5%. Check whether the planned transfer still covers the food basket."
    if change_pct < -5:
        return "Falling", "The price is expected to fall by more than 5%. The planned transfer should buy more of this item."
    return "Stable", "The price is expected to stay within 5% of last month's price."


@app.get("/", include_in_schema=False)
def root():
    return RedirectResponse(url="/docs")


@app.post("/predict", response_model=PredictionOutput)
def predict(item: MarketInput):
    row = pd.DataFrame([item.model_dump()])[FEATURES]
    with lock:
        price = float(state["model"].predict(row)[0])
    price = round(max(price, 1.0), 1)
    change = round((price / item.price_last_month - 1) * 100, 1)
    alert, message = price_alert(change)
    return PredictionOutput(predicted_price_rwf_per_kg=price, change_vs_last_month_pct=change,
                            price_alert=alert, message=message)


@app.post("/retrain", response_model=RetrainOutput)
async def retrain(file: UploadFile = File(description="CSV with the same columns as the training data: the 8 features plus price.")):
    if not (file.filename or "").lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="Please upload a .csv file.")
    try:
        new = pd.read_csv(io.BytesIO(await file.read()))
    except Exception:
        raise HTTPException(status_code=400, detail="Could not read the file as CSV.")

    missing = [c for c in FEATURES + [TARGET] if c not in new.columns]
    if missing:
        raise HTTPException(status_code=422, detail=f"CSV is missing required columns: {missing}")
    rows_received = len(new)
    new = new[FEATURES + [TARGET]].dropna()

    # validate every row with the same rules as /predict, plus a valid target
    errors = []
    for line, rec in zip(new.index + 2, new.to_dict("records")):  # +2 = header row + 1-based numbering
        try:
            MarketInput.model_validate({k: _py(rec[k]) for k in FEATURES}, strict=False)
        except ValidationError as e:
            err = e.errors()[0]
            errors.append(f"line {line}: {'.'.join(str(p) for p in err['loc'])}: {err['msg']}")
            continue
        if not 0 < rec[TARGET] <= 20000:
            errors.append(f"line {line}: price must be above 0 and at most 20000 RWF per kg")
    if errors:
        raise HTTPException(status_code=422, detail={"message": f"{len(errors)} invalid row(s)", "errors": errors[:10]})
    if new.empty:
        raise HTTPException(status_code=422, detail="No usable rows in the CSV.")
    new[["year", "month"]] = new[["year", "month"]].astype(int)

    with lock:
        result = retrain_model(state["model"], state["data"], new, FEATURES, TARGET)
        state["model"], state["data"] = result.model, result.data  # /predict uses the new model immediately
        try:
            joblib.dump(result.model, MODEL_PATH)
            result.data.to_csv(DATA_PATH, index=False)
        except OSError:
            pass  # read-only disk is fine: the model in memory is already updated

    return RetrainOutput(
        message="Model retrained. /predict now uses the updated model.",
        method=result.method,
        rows_received=rows_received,
        rows_used=len(new),
        total_training_rows=len(result.data),
        mse_on_new_rows_before=round(result.mse_before, 1),
        mse_on_new_rows_after=round(result.mse_after, 1),
    )


def _py(v):
    """Convert numpy values to plain Python values so Pydantic can validate CSV rows."""
    if isinstance(v, np.integer):
        return int(v)
    if isinstance(v, np.floating):
        return float(v)
    return v
